package main

func Generate(ch chan<- int) {
	for i := 2; ; i++ {
		ch <- i
	}
}
func Filter(in <-chan int, out chan<- int, prime int) {
	for {
		i := <-in
		if i%prime != 0 {
			out <- i
		}
	}
}

/*
*

	2,3,4,5,6,7,8,9,10,...

Generate ──────────────────────────► ch0

	    │
	    ▼
	┌───────┐
	│  %2   │
	└───────┘
	    │ ch1
	    ▼
	┌───────┐
	│  %3   │
	└───────┘
	    │ ch2
	    ▼
	┌───────┐
	│  %5   │
	└───────┘
	    │ ch3
	    ▼
	┌───────┐
	│  %7   │
	└───────┘
	    │ ch4
	    ▼
	  main

2  ─► (管道还是空的，main 直接读) ─────────────────────► ★ 素数

	└─ 读到后建立 [%2]

3  ─► [%2]✓ ─► (出口) ──────────────────────────────► ★ 素数

	└─ 读到后建立 [%3]

4  ─► [%2] ✗@%2  (4%2==0，丢弃)

	╳

5  ─► [%2]✓ ─► [%3]✓ ─► (出口) ─────────────────────► ★ 素数

	└─ 读到后建立 [%5]

6  ─► [%2] ✗@%2  (6%2==0，丢弃)

	╳

7  ─► [%2]✓ ─► [%3]✓ ─► [%5]✓ ─► (出口) ────────────► ★ 素数

	└─ 读到后建立 [%7]

8  ─► [%2] ✗@%2  (8%2==0，丢弃)

	╳

9  ─► [%2]✓ ─► [%3] ✗@%3  (9%3==0，丢弃)

	╳

10 ─► [%2] ✗@%2  (10%2==0，丢弃)

	╳
*/
func main() {
	ch := make(chan int)
	go Generate(ch)

	for i := 0; i < 10; i++ {
		prime := <-ch
		print(prime, "\n")
		ch1 := make(chan int)
		go Filter(ch, ch1, prime)
		ch = ch1
	}
}
